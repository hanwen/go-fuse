#!/bin/bash
# Run go-fuse tests inside a FreeBSD VM under QEMU. Needs no root.
#
# The test binaries are cross-compiled on the host and handed to the VM
# on a NoCloud cloud-init ISO; the FreeBSD BASIC-CLOUDINIT image runs
# the user-data script from that ISO at boot (nuageinit). The script
# runs the tests, tars logs and exit statuses onto a scratch disk, and
# powers off. The host then unpacks the scratch disk and reports.
#
# Usage: ./test-freebsd.bash [package ...]   (default: ./posixtest ./fs)
#
# Environment:
#   FREEBSD_VERSION   release to test against (default 15.1)
#   FREEBSD_IMAGE_URL override the image download URL
#   TEST_ARGS         extra flags for the test binaries (e.g. -test.run=Foo)
#   VM_TIMEOUT        wall-clock limit for the VM (default 30m)
#   OUT_DIR           where to leave logs (default: a fresh tmp dir)
#
# Exit status is 0 only if every test binary exited with 0.

set -eu -o pipefail

cd "$(dirname "$0")"

FREEBSD_VERSION=${FREEBSD_VERSION:-15.1}
IMAGE_NAME=FreeBSD-${FREEBSD_VERSION}-RELEASE-amd64-BASIC-CLOUDINIT-ufs.raw
FREEBSD_IMAGE_URL=${FREEBSD_IMAGE_URL:-https://download.freebsd.org/releases/VM-IMAGES/${FREEBSD_VERSION}-RELEASE/amd64/Latest/${IMAGE_NAME}.xz}
VM_TIMEOUT=${VM_TIMEOUT:-30m}
TEST_ARGS=${TEST_ARGS:-}

CACHE_DIR=$HOME/.cache/go-fuse-freebsd
BASE_IMAGE=$CACHE_DIR/$IMAGE_NAME

if [[ $# -gt 0 ]]; then
  PACKAGES=("$@")
else
  PACKAGES=(./posixtest ./fs)
fi

for tool in qemu-system-x86_64 qemu-img xz curl; do
  command -v $tool >/dev/null || { echo "missing $tool" >&2; exit 2; }
done
MKISO=
for tool in xorriso genisoimage mkisofs; do
  if command -v $tool >/dev/null; then MKISO=$tool; break; fi
done
[[ -n "$MKISO" ]] || { echo "need xorriso, genisoimage or mkisofs" >&2; exit 2; }

mkdir -p "$CACHE_DIR"
WORK=$(mktemp -d "$CACHE_DIR/run.XXXXXXXX")
OUT_DIR=${OUT_DIR:-$WORK/results}
mkdir -p "$OUT_DIR"
trap 'rm -rf "$WORK/vm.qcow2" "$WORK/results.img" "$WORK/cidata" "$WORK/cidata.iso"; rmdir "$WORK" 2>/dev/null || true' EXIT

# 1. Fetch the pristine image once. It is never written to; each run
# boots a qcow2 overlay on top of it.
if [[ ! -f "$BASE_IMAGE" ]]; then
  echo "downloading $FREEBSD_IMAGE_URL"
  curl -fL --output "$BASE_IMAGE.xz.part" "$FREEBSD_IMAGE_URL"
  xz -d -c "$BASE_IMAGE.xz.part" > "$BASE_IMAGE.part"
  mv "$BASE_IMAGE.part" "$BASE_IMAGE"
  rm -f "$BASE_IMAGE.xz.part"
fi
qemu-img create -q -f qcow2 -F raw -b "$BASE_IMAGE" "$WORK/vm.qcow2" 10G

# 2. Build test binaries and the cloud-init ISO.
CIDATA=$WORK/cidata
mkdir -p "$CIDATA/bin"
names=()
for pkg in "${PACKAGES[@]}"; do
  name=$(basename "$pkg")
  GOOS=freebsd GOARCH=amd64 CGO_ENABLED=0 go test -c -o "$CIDATA/bin/$name.test" "$pkg"
  names+=("$name")
done

cat > "$CIDATA/meta-data" <<EOF
instance-id: go-fuse-test-$(basename "$WORK")
local-hostname: go-fuse-test
EOF

cat > "$CIDATA/user-data" <<EOF
#!/bin/sh
# Generated by test-freebsd.bash; runs as root at boot.
exec > /dev/console 2>&1
RES=/root/results
mkdir -p \$RES /root/gofuse /media/gofuse
mount -t cd9660 -o ro /dev/iso9660/[cC][iI][dD][aA][tT][aA] /media/gofuse
cp /media/gofuse/bin/*.test /root/gofuse/
umount /media/gofuse
chmod +x /root/gofuse/*.test
uname -a > \$RES/uname.txt
kldload fusefs
cd /root/gofuse
for t in ${names[*]}; do
  echo "go-fuse: running \$t"
  ./\$t.test -test.v -test.timeout 10m $TEST_ARGS > \$RES/\$t.log 2>&1
  echo \$? > \$RES/\$t.status
  echo "go-fuse: \$t exited \$(cat \$RES/\$t.status)"
done
echo done > \$RES/finished
tar -cf /dev/vtbd1 -C \$RES .
sync
shutdown -p now
EOF

case $MKISO in
xorriso) xorriso -report_about SORRY -as mkisofs -quiet -V cidata -J -R -o "$WORK/cidata.iso" "$CIDATA" ;;
*) $MKISO -quiet -V cidata -J -R -o "$WORK/cidata.iso" "$CIDATA" ;;
esac

# 3. Boot. Disk order matters: vtbd0 = system, vtbd1 = results.
truncate -s 256M "$WORK/results.img"

ACCEL=(-accel tcg)
if [[ -w /dev/kvm ]]; then
  ACCEL=(-accel kvm -cpu host)
else
  echo "/dev/kvm not usable; falling back to slow TCG emulation" >&2
fi

echo "booting FreeBSD $FREEBSD_VERSION; console log in $OUT_DIR/console.log"
vm_status=0
timeout --foreground "$VM_TIMEOUT" qemu-system-x86_64 \
  "${ACCEL[@]}" \
  -m 2G -smp 2 \
  -display none -serial stdio -monitor none \
  -no-reboot \
  -drive file="$WORK/vm.qcow2",format=qcow2,if=virtio \
  -drive file="$WORK/results.img",format=raw,if=virtio \
  -drive file="$WORK/cidata.iso",format=raw,if=virtio,readonly=on \
  -nic none \
  < /dev/null 2>&1 | tee "$OUT_DIR/console.log" || vm_status=$?

# 4. Report.
tar -xf "$WORK/results.img" -C "$OUT_DIR" 2>/dev/null || true

if [[ ! -f "$OUT_DIR/finished" ]]; then
  echo "VM did not finish the test run (qemu/timeout exit $vm_status); see $OUT_DIR/console.log" >&2
  exit 1
fi

overall=0
echo
echo "FreeBSD $FREEBSD_VERSION results ($(cat "$OUT_DIR/uname.txt" 2>/dev/null)):"
for t in "${names[@]}"; do
  st=$(cat "$OUT_DIR/$t.status" 2>/dev/null || echo missing)
  if [[ "$st" == 0 ]]; then
    echo "  ok    $t"
  else
    echo "  FAIL  $t (exit $st)"
    grep -E '^\s*--- FAIL' "$OUT_DIR/$t.log" 2>/dev/null | sed 's/^/        /' || true
    overall=1
  fi
done
echo "logs in $OUT_DIR"
exit $overall
